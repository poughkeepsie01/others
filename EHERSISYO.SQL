--EMPLOYEE NAME AND SALARY LOOK UP
CREATE OR REPLACE PROCEDURE EMP_LU(EMPLOYEE_NUMBER NUMBER) IS 
CURSOR EMP_MST_LIST IS 
SELECT * FROM EMPLOYEES;

TYPE EMP_ARR IS TABLE OF EMP_MST_LIST%ROWTYPE INDEX BY PLS_INTEGER;
EMP_DATA EMP_ARR;

BEGIN 

OPEN EMP_MST_LIST; 
FETCH EMP_MST_LIST BULK COLLECT INTO  EMP_DATA;
CLOSE EMP_MST_LIST;

DBMS_OUTPUT.PUT_LINE('EMPLOYEE_NAME: ' || EMP_DATA(EMPLOYEE_NUMBER).FIRST_NAME 
                                                       || ' SALARY: ' || EMP_DATA(EMPLOYEE_NUMBER).SALARY );


EXCEPTION
WHEN NO_DATA_FOUND THEN 
DBMS_OUTPUT.PUT_LINE('NO EMPLOYEE FOUND');

END;

--EMPLOYEE SALARY STATUS
CREATE OR REPLACE PROCEDURE EMP_SALARY_VAL IS 

CURSOR EMP_MST_LIST IS 
SELECT * FROM EMPLOYEES;

TYPE EMP_ARR IS TABLE OF EMP_MST_LIST%ROWTYPE INDEX BY PLS_INTEGER;
EMP_DATA EMP_ARR;

 FUNCTION SALARY_VAL(V_SALARY NUMBER) RETURN VARCHAR2 IS 
 BEGIN 
 IF V_SALARY > 10000 THEN 
      RETURN 'HIGH';
 ELSIF V_SALARY < 5000 THEN 
      RETURN 'LOW';
  ELSE RETURN 'MEDIUM';
  END IF;
END;

BEGIN 
 OPEN EMP_MST_LIST;
 FETCH EMP_MST_LIST BULK COLLECT INTO EMP_DATA;
 CLOSE EMP_MST_LIST;
 
 FOR i in EMP_DATA.FIRST .. EMP_DATA.LAST LOOP
 DBMS_OUTPUT.PUT_LINE ('EMPLOYEE_NAME: ' || EMP_DATA(i).FIRST_NAME ||
                                                          ' SALARY STATUS: ' || SALARY_VAL(EMP_DATA(i).SALARY) );
 END LOOP;

EXCEPTION 
WHEN OTHERS THEN 
DBMS_OUTPUT.PUT_LINE (SQLERRM);

END;

--SALARY ADJUSTMENT
CREATE OR REPLACE PROCEDURE DEPT_SAL_ADJ(V_JOB_ID VARCHAR2) IS 

COUNTER NUMBER(10) := 0;

CURSOR EMP_MST_LIST IS 
SELECT * FROM EMPLOYEES
WHERE JOB_ID = V_JOB_ID;

TYPE EMP_ARR IS TABLE OF EMP_MST_LIST%ROWTYPE INDEX BY PLS_INTEGER;
EMP_DATA EMP_ARR;

 FUNCTION SALARY_VAL(V_SALARY NUMBER) RETURN NUMBER  IS 
 BEGIN 
 IF V_SALARY < 30000 THEN 
      RETURN V_SALARY + (V_SALARY * 0.15);
 ELSIF V_SALARY > 50000 THEN 
      RETURN V_SALARY + (V_SALARY * 0.05);
  ELSE RETURN  V_SALARY + (V_SALARY * 0.10);
  END IF;
END;



BEGIN 
 OPEN EMP_MST_LIST;
 FETCH EMP_MST_LIST BULK COLLECT INTO EMP_DATA;
 CLOSE EMP_MST_LIST;
 
 FOR i in EMP_DATA.FIRST .. EMP_DATA.LAST LOOP
 DBMS_OUTPUT.PUT_LINE ('EMPLOYEE_NAME: ' || EMP_DATA(i).FIRST_NAME ||
                                                          ' NEW SALARY: ' || SALARY_VAL(EMP_DATA(i).SALARY) ||
                                                          ' OLD SALARY: ' || EMP_DATA(i).SALARY);
                                                          
                                                           COUNTER:= i;
 END LOOP;
 
 DBMS_OUTPUT.PUT_LINE (COUNTER|| ' ');

EXCEPTION 
WHEN OTHERS THEN 
DBMS_OUTPUT.PUT_LINE (SQLERRM);

END;

